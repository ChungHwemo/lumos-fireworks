export function weekday(date: string, lang: Lang): string {
  const [year, month, day] = date.split("-").map(Number);
  const utc = new Date(Date.UTC(year, month - 1, day, 3, 0, 0));
  return new Intl.DateTimeFormat(lang === "ko" ? "ko-KR" : "en-US", {
    weekday: "short",
    timeZone: "Asia/Tokyo",
  }).format(utc);
}
