export type Dict = Record<keyof typeof ko, string>;

export function isLang(value: unknown): value is Lang {
  return value === "ko" || value === "ja" || value === "en";
}

export const localeTag: Record<Lang, string> = {
  ko: "ko-KR",
  ja: "ja-JP",
  en: "en-US",
};

export function weekday(date: string, lang: Lang): string {
  const [year, month, day] = date.split("-").map(Number);
  const utc = new Date(Date.UTC(year, month - 1, day, 3, 0, 0));
  return new Intl.DateTimeFormat(localeTag[lang], {
    weekday: "short",
    timeZone: "Asia/Tokyo",
  }).format(utc);
}
